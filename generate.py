def generate_sitemap():
    urls = [f"  <url><loc>{SITE_URL}/</loc><lastmod>{TODAY}</lastmod><priority>1.0</priority></url>"]
    for p in PHRASES:
        urls.append(f"  <url><loc>{SITE_URL}/phrases/{p['slug']}.html</loc><lastmod>{TODAY}</lastmod><priority>0.8</priority></url>")

